const KEY = 'nexus_lang';
let lang = 'en';
try { lang = localStorage.getItem(KEY) || (navigator.language || 'en').slice(0, 2); } catch { /* storage blocked */ }
if (!['en', 'fr'].includes(lang)) lang = 'en';

const EN = new Map(Object.entries(FR).map(([k, v]) => [v, k])); // reverse, so switching back restores English
const lookup = (s) => {
  const core = s.trim();
  if (!core) return null;
  const hit = lang === 'fr' ? FR[core] : EN.get(core);
  return hit ? s.replace(core, hit) : null;
};

function apply(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n = root;
  while (n) {
    if (n.nodeType === 3) { const t = lookup(n.nodeValue); if (t) n.nodeValue = t; }
    else if (n.nodeType === 1 && !/^(SCRIPT|STYLE|VIDEO)$/.test(n.tagName)) {
      for (const a of ['placeholder', 'aria-label', 'title']) { const v = n.getAttribute(a); if (v) { const t = lookup(v); if (t) n.setAttribute(a, t); } }
    }
    n = walker.nextNode();
  }
}

let busy = false;
const mo = new MutationObserver((muts) => {
  if (busy || lang === 'en') return;
  busy = true;
  for (const m of muts) {
    if (m.type === 'characterData') { const t = lookup(m.target.nodeValue); if (t) m.target.nodeValue = t; }
    else m.addedNodes.forEach((x) => apply(x));
  }
  busy = false;
});
mo.observe(document.body, { childList: true, subtree: true, characterData: true });

export const i18n = {
  get lang() { return lang; },
  set(l) {
    lang = l;
    try { localStorage.setItem(KEY, l); } catch { /* ignore */ }
    document.documentElement.lang = l;
    busy = true; apply(document.body); busy = false;
  },
  toggle() { this.set(lang === 'fr' ? 'en' : 'fr'); },
  t: (s) => lookup(s) ?? s,
};
